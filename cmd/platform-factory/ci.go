package main

import (
	"context"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"runtime"
	"strings"
	"time"

	initramfsapp "github.com/CYPT71/platform-factory/internal/app/microvminitramfs"
	"github.com/CYPT71/platform-factory/internal/ciguard"
	"github.com/CYPT71/platform-factory/internal/directboot"
	"github.com/CYPT71/platform-factory/internal/gitlabci"
	"github.com/CYPT71/platform-factory/internal/project"
)

func runCI(args []string, stdout, stderr io.Writer) int {
	if len(args) == 0 || args[0] == "--help" {
		fmt.Fprintln(stdout, "usage: pf ci <lock|plan-lock|verify|check|gitlab|run|package|boot> [OPTIONS]")
		return 0
	}
	flags := flag.NewFlagSet("ci "+args[0], flag.ContinueOnError)
	flags.SetOutput(stderr)
	dir := flags.String("dir", ".", "project root")
	filename := flags.String("lock", "pf.inputs.lock.json", "recursive inputs lock")
	output := flags.String("output", "", "new output file or directory")
	config := flags.String("config", "pf.yaml", "project or CI config")
	layout := flags.String("layout", "", "OCI layout")
	platform := flags.String("platform", "linux/amd64", "OCI platform")
	initBinary := flags.String("init", "", "trusted PID 1 binary")
	distroless := flags.Bool("distroless", false, "require a static nonroot application with no additional files")
	phase := flags.String("phase", "build", "GitLab runner phase")
	var paths repeatedFlag
	flags.Var(&paths, "path", "input file or directory; repeatable")
	kernel := flags.String("kernel", "", "pinned kernel path")
	kd := flags.String("kernel-digest", "", "kernel SHA-256")
	initrd := flags.String("initramfs", "", "pinned initramfs path")
	id := flags.String("initramfs-digest", "", "initramfs SHA-256")
	ready := flags.String("ready", "", "literal guest readiness marker")
	timeout := flags.Duration("timeout", 45*time.Second, "native boot deadline")
	if err := flags.Parse(args[1:]); err != nil {
		return 2
	}
	if flags.NArg() != 0 {
		return 2
	}
	fail := func(err error) int { fmt.Fprintln(stderr, "CI:", err); return 1 }
	switch args[0] {
	case "package":
		if *output == "" || *layout == "" || *initBinary == "" {
			return fail(errors.New("package requires --layout, --init and --output"))
		}
		result, err := initramfsapp.Assemble(*layout, *platform, "", *initBinary, nil, *output)
		if err != nil {
			return fail(err)
		}
		if err := json.NewEncoder(stdout).Encode(result); err != nil {
			return fail(err)
		}
		return 0
	case "plan-lock":
		if *output == "" {
			return fail(errors.New("--output requires a new reviewed project lock"))
		}
		configPath := *config
		if !filepath.IsAbs(configPath) {
			configPath = filepath.Join(*dir, configPath)
		}
		loaded, err := project.Load(configPath)
		if err != nil {
			return fail(err)
		}
		files, err := loaded.ImageFiles()
		if err != nil {
			return fail(err)
		}
		if loaded.Config.Profile != "static" || loaded.Config.Isolation == "microvm" || len(files) != 0 {
			return fail(errors.New("plan-lock supports static OCI projects without extra files; boot pins belong in the separate CI config"))
		}
		if err := loaded.VerifyFreezeInventory(); err != nil {
			return fail(err)
		}
		raw, err := os.ReadFile(loaded.File)
		if err != nil {
			return fail(err)
		}
		digest, err := project.CanonicalManifestDigest(raw)
		if err != nil {
			return fail(err)
		}
		file, err := os.OpenFile(*output, os.O_CREATE|os.O_EXCL|os.O_WRONLY, 0644)
		if err != nil {
			return fail(err)
		}
		err = json.NewEncoder(file).Encode(project.Lock{Version: project.CurrentLockVersion, PlanDigest: digest})
		closeErr := file.Close()
		if err != nil {
			return fail(err)
		}
		if closeErr != nil {
			return fail(closeErr)
		}
		return 0
	case "lock":
		if *output == "" {
			return fail(errors.New("--output is required; locks are never regenerated by CI"))
		}
		lock, err := ciguard.Snapshot(*dir, paths)
		if err != nil {
			return fail(err)
		}
		absolute, _ := filepath.Abs(*output)
		root, _ := filepath.Abs(*dir)
		for _, p := range paths {
			selected := filepath.Join(root, filepath.FromSlash(p))
			if absolute == selected || strings.HasPrefix(absolute, selected+string(filepath.Separator)) {
				return fail(errors.New("lock output cannot be inside a selected input"))
			}
		}
		file, err := os.OpenFile(*output, os.O_CREATE|os.O_EXCL|os.O_WRONLY, 0644)
		if err != nil {
			return fail(err)
		}
		err = json.NewEncoder(file).Encode(lock)
		closeErr := file.Close()
		if err != nil {
			return fail(err)
		}
		if closeErr != nil {
			return fail(closeErr)
		}
		return 0
	case "verify":
		lock, err := ciguard.Read(*filename)
		if err != nil {
			return fail(err)
		}
		if err := ciguard.Verify(*dir, lock); err != nil {
			return fail(err)
		}
		fmt.Fprintln(stdout, "CI inputs verified")
		return 0
	case "check":
		configPath := *config
		if !filepath.IsAbs(configPath) {
			configPath = filepath.Join(*dir, configPath)
		}
		loaded, err := project.Discover(*dir, configPath)
		if err != nil {
			return fail(err)
		}
		if *distroless {
			files, err := loaded.ImageFiles()
			if err != nil {
				return fail(err)
			}
			if loaded.Config.Profile != "static" || (loaded.Config.User != "65532" && loaded.Config.User != "65532:65532") || len(files) != 0 {
				return fail(errors.New("distroless requires a static nonroot application without extra files"))
			}
		}
		lock, err := project.LoadLock(loaded.AdjacentLockPath())
		if err != nil {
			return fail(err)
		}
		if lock.Version != project.CurrentLockVersion {
			return fail(errors.New("CI requires a v2 pf.lock"))
		}
		if err := loaded.VerifyAdjacentLock(); err != nil {
			return fail(err)
		}
		if err := loaded.VerifyFreezeInventory(); err != nil {
			return fail(err)
		}
		fmt.Fprintln(stdout, "project lock and freeze inventory verified")
		return 0
	case "gitlab":
		if *output == "" {
			return fail(errors.New("--output requires a new directory"))
		}
		if err := os.Mkdir(*output, 0755); err != nil {
			return fail(err)
		}
		entries, err := gitlabci.Assets.ReadDir("assets")
		if err != nil {
			return fail(err)
		}
		for _, entry := range entries {
			data, err := gitlabci.Assets.ReadFile("assets/" + entry.Name())
			if err != nil {
				return fail(err)
			}
			if err := os.WriteFile(filepath.Join(*output, entry.Name()), data, 0644); err != nil {
				return fail(err)
			}
		}
		fmt.Fprintln(stdout, "GitLab CI assets generated; vendor the component and commit reviewed input locks")
		return 0
	case "run":
		executable, err := os.Executable()
		if err != nil {
			return fail(err)
		}
		script, err := gitlabci.Assets.ReadFile("assets/runner.py")
		if err != nil {
			return fail(err)
		}
		return runPythonHook(script, []string{"--pf", executable, "--config", *config, "--phase", *phase}, os.Stdin, stdout, stderr)
	case "boot":
		if *ready == "" || len(*ready) > 256 || *timeout < time.Second || *timeout > 5*time.Minute {
			return fail(errors.New("boot requires a 1..256 byte readiness marker and a 1s..5m timeout"))
		}
		ctx, cancel := context.WithTimeout(context.Background(), *timeout)
		defer cancel()
		commandLine := "console=ttyS0,115200 earlycon=uart,io,0x3f8,115200 panic=0 rdinit=/sbin/init"
		if runtime.GOOS == "darwin" {
			commandLine = "console=hvc0 earlycon=hvc0 panic=0 rdinit=/sbin/init"
		}
		result, err := directboot.Run(ctx, directboot.Config{KernelPath: *kernel, KernelDigest: *kd, InitramfsPath: *initrd, InitramfsDigest: *id, CommandLine: commandLine, MemoryMiB: 512, VCPUs: 1})
		if !strings.Contains(string(result.Serial), *ready) || (err != nil && !errors.Is(err, context.DeadlineExceeded)) {
			if err == nil {
				err = errors.New("guest readiness marker not observed")
			}
			return fail(err)
		}
		fmt.Fprintln(stdout, "native microVM readiness verified")
		return 0
	default:
		return 2
	}
}
